def compact_tree(estimator,classifier_tree=False):
    t=estimator.tree_
    def node(i):
        if t.children_left[i]<0:
            return [float(v) for v in t.value[i,0]] if classifier_tree else int(t.n_node_samples[i])
        return [int(t.feature[i]),float(t.threshold[i]),node(t.children_left[i]),node(t.children_right[i])]
    return node(0)
