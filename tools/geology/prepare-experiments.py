def tile(seed):
    r = np.random.default_rng(seed)
    yy, xx = np.mgrid[:H,:W]
    phase = r.uniform(-5,5)
    b1 = 14 + 4*np.sin(yy/6+phase) + .12*yy
    b2 = 31 + 3*np.sin(yy/8+phase) - .09*yy
    label = (xx > b1).astype(int) + (xx > b2).astype(int)
    vegetation = ((xx-r.uniform(8,42))**2/38+(yy-r.uniform(6,25))**2/18 < 1)
    illum = .88+.12*np.sin(xx/15+phase)+.06*np.cos(yy/10)
    bands = means[label] * illum[...,None] + r.normal(0,.029,(H,W,6))
    shadow = (xx+yy*1.3>57)&(xx<39)
    bands[shadow] *= .76
    bands[vegetation] = np.array([.09,.16,.07,.52,.27,.13])+r.normal(0,.02,(vegetation.sum(),6))
    bands = np.clip(bands, .01, .95)
    feature = np.concatenate([bands, (bands[:,:,4]/bands[:,:,5])[:,:,None], (bands[:,:,3]/bands[:,:,0])[:,:,None]],axis=2)
    label[vegetation] = 3
    return bands, feature, label

